import numpy as np

# 首先创建两个矩阵arr_1和arr_2来实现矩阵的加、减、除运算
arr_1 = np.matrix([[1, 2, 5, 6], [3, 4, 7, 8]])
arr_2 = np.matrix([[1, 2, 5, 6], [3, 4, 7, 8]])     # 创建两个矩阵

# 矩阵相加
print(arr_1 + arr_2)
# 输出:
# [[2 4 10 12]
#  [6 8 14 16]]

# 矩阵相减
print(arr_1 - arr_2)
# 输出:
# [[0 0 0 0]
#  [0 0 0 0]]

# 矩阵相除
print(arr_1 / arr_2)
# 输出:
# [[1. 1. 1. 1.]
#  [1. 1. 1. 1.]]