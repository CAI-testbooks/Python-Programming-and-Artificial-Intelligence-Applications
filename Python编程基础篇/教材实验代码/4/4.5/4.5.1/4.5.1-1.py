str1 = 'Hello'       # 单引号定义字符串
str2 = "world!"      # 双引号定义字符串
print(str1, str2)
# 运行结果: Hello world!

# 三单引号 ''' 多行字符串，可以保留换行
str3 = '''Q: 我们为什么要学习 Python?
A: 因为 Python 简单易学且应用领域广泛。'''

# 三双引号 """ 多行字符串，同样保留换行
str4 = """Q: 我们应该如何学习 Python?
A: 可以通过官方文档、在线课程和各类相关书籍来学习 Python。"""

print(str3)
print(str4)
