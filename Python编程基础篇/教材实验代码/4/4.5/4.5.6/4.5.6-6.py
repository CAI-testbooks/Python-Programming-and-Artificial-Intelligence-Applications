context = 'python is my FAVORITE language. python is easy to learn.'
print(context.capitalize())    # 首字母大写
# 运行结果: Python is my favorite language. python is easy to learn.
print(context.title())         # 每个单词首字母大写
# 运行结果: Python Is My Favorite Language. Python Is Easy To Learn.
print(context.lower())         # 全部小写
# 运行结果: python is my favorite language. python is easy to learn.
print(context.upper())         # 全部大写
# 运行结果: PYTHON IS MY FAVORITE LANGUAGE. PYTHON IS EASY TO LEARN.
print(context.swapcase())      # 大小写互换
# 运行结果: PYTHON IS MY favorite LANGUAGE. PYTHON IS EASY TO LEARN.