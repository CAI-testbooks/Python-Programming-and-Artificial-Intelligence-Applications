# 例如，如果想定义一个变量，表示学生的年龄，其值为20，可以这样编写代码：
student_age = 20
print(student_age)

# 如果想要修改学生的年龄为18岁，则可以重新给 student_age 赋值：
student_age = 20
print(student_age)
student_age = 18
print(student_age)

# 另外，Python支持同时对多个变量进行赋值操作：
student_age, student_score = 20, 90
print(student_age)
print(student_score)
