# 对字符串指定最小宽度
print('%10s' % 'python')

# 对整数指定最小宽度为7
print('%7d' % 123)

# 对浮点数指定最小宽度为7，精度为3
print('%7.3f' % 1.23456)

# 对浮点数指定最小宽度为7，精度为3，且左侧空位用0填充
print('%07.3f' % 1.23456)

# 对浮点数指定最小宽度为7，精度为3，左侧空位用0填充，正数加正号（正号也占一个宽度）
print('%+07.3f' % 1.23456)

# 对浮点数指定最小宽度为7，精度为3，左对齐输出
print('%-7.3f' % 1.23456)

# 在八进制、十六进制数前添加 0o、0x 或 0X
print('%#o,%#x,%#X' % (10, 10, 10))

