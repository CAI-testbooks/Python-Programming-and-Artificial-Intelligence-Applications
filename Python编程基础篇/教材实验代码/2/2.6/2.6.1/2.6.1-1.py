# 顺序结构示例，顺序计算 (10+20)*2-5
# 第一步：定义变量并赋值
a = 10
b = 20

# 第二步：计算10+20
sum_result = a + b

# 第三步：计算 (10+20)*2
product_result = sum_result * 2    # 使用sum_result进行计算

# 第四步：计算 (10+20)*2-5
final_result = product_result - 5  # 使用product_result进行计算

# 第五步：输出最终结果
print("计算结果为：", final_result)
